/* ==========================================================
   READ THE CATEGORY FROM THE URL

   Examples:
   gallery.html?category=events
   gallery.html?category=corporate
   gallery.html?category=lifestyle
   ========================================================== */

const parameters = new URLSearchParams(window.location.search);
const category = parameters.get("category");

const selectedGallery = galleries[category];

const galleryTitle = document.querySelector("#gallery-title");
const galleryDescription = document.querySelector(
  "#gallery-description",
);
const mediaGrid = document.querySelector("#media-grid");
const galleryError = document.querySelector("#gallery-error");

/* ==========================================================
   CREATE AN IMAGE
   ========================================================== */

function createImage(item) {
  const image = document.createElement("img");

  image.src = item.src;
  image.alt = item.alt || "";
  image.loading = "lazy";

  return image;
}

/* ==========================================================
   CREATE A VIDEO
   ========================================================== */

function createVideo(item) {
  const video = document.createElement("video");

  video.controls = true;
  video.playsInline = true;
  video.preload = "metadata";

  const source = document.createElement("source");

  source.src = item.src;
  source.type = getVideoType(item.src);

  video.append(source);

  return video;
}

/* ==========================================================
   DETECT THE VIDEO TYPE
   ========================================================== */

function getVideoType(filename) {
  const extension = filename
    .split(".")
    .pop()
    .toLowerCase();

  if (extension === "webm") {
    return "video/webm";
  }

  if (extension === "mov") {
    return "video/quicktime";
  }

  return "video/mp4";
}

/* ==========================================================
   CREATE ONE GALLERY ITEM
   ========================================================== */

function createMediaItem(item) {
  const figure = document.createElement("figure");

  figure.classList.add("media-item");

  if (item.size === "wide") {
    figure.classList.add("media-wide");
  }

  if (item.type === "video") {
    figure.append(createVideo(item));
  } else {
    figure.append(createImage(item));
  }

  if (item.caption) {
    const caption = document.createElement("figcaption");

    caption.textContent = item.caption;

    figure.append(caption);
  }

  return figure;
}

/* ==========================================================
   DISPLAY THE SELECTED GALLERY
   ========================================================== */

function displayGallery() {
  if (!selectedGallery) {
    document.title = "Gallery not found — Homesick Creative";

    mediaGrid.hidden = true;
    galleryError.hidden = false;

    return;
  }

  galleryTitle.textContent = selectedGallery.title;
  galleryDescription.textContent =
    selectedGallery.description;

  document.title =
    `${selectedGallery.title} — Homesick Creative`;

  selectedGallery.media.forEach((item) => {
    const mediaItem = createMediaItem(item);

    mediaGrid.append(mediaItem);
  });
}

displayGallery();
